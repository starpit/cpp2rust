#include <math.h>

double f1(double x) { return cos(x); }

double f2(double x) { return round(x); }

double f3(double x) { return sin(x); }

double f4(double x) { return ceil(x); }

double f5(double x) { return floor(x); }

double f6(double x, double y) { return pow(x, y); }

double f7(double x) { return sqrt(x); }

double f8(double x, double y) { return fmod(x, y); }
